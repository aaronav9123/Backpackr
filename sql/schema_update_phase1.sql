-- ============================================================
-- Backpackr Phase 1 Schema Update
-- Community Contribution + Ratings + Saved Places
-- Run this against the existing Oracle schema (USERS, PLACES,
-- TRIPS, TRIP_STOPS already exist). Safe to run once.
-- ============================================================

-- 1. Extend PLACES so every place can be community-contributed
--    and carry the extra detail the new UI needs.
ALTER TABLE PLACES ADD (
    ADDRESS         VARCHAR2(500),
    AVG_COST        NUMBER(10,2) DEFAULT 0,
    OPENING_TIME    VARCHAR2(100),
    BEST_TIME       VARCHAR2(100),
    MAPS_LINK       VARCHAR2(500),
    ADDED_BY        NUMBER,
    CREATED_DATE    DATE DEFAULT SYSDATE
);

ALTER TABLE PLACES ADD CONSTRAINT FK_PLACES_ADDED_BY
    FOREIGN KEY (ADDED_BY) REFERENCES USERS(USER_ID);

-- 2. Multiple photos per place (community uploads)
CREATE TABLE PLACE_IMAGES (
    IMAGE_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PLACE_ID        NUMBER NOT NULL,
    IMAGE_URL       VARCHAR2(500) NOT NULL,
    UPLOADED_BY     NUMBER,
    CREATED_DATE    DATE DEFAULT SYSDATE,
    CONSTRAINT FK_IMG_PLACE FOREIGN KEY (PLACE_ID) REFERENCES PLACES(PLACE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_IMG_USER FOREIGN KEY (UPLOADED_BY) REFERENCES USERS(USER_ID)
);

-- 3. Community star ratings (one rating per user per place, upsert-able)
CREATE TABLE RATINGS (
    RATING_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PLACE_ID        NUMBER NOT NULL,
    USER_ID         NUMBER NOT NULL,
    STARS           NUMBER(1) NOT NULL CHECK (STARS BETWEEN 1 AND 5),
    CREATED_DATE    DATE DEFAULT SYSDATE,
    CONSTRAINT FK_RATING_PLACE FOREIGN KEY (PLACE_ID) REFERENCES PLACES(PLACE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_RATING_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT UQ_RATING_USER_PLACE UNIQUE (PLACE_ID, USER_ID)
);

-- 4. Saved / bookmarked places ("Saved Places" sidebar item)
CREATE TABLE SAVED_PLACES (
    SAVED_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER NOT NULL,
    PLACE_ID        NUMBER NOT NULL,
    SAVED_DATE      DATE DEFAULT SYSDATE,
    CONSTRAINT FK_SAVED_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_SAVED_PLACE FOREIGN KEY (PLACE_ID) REFERENCES PLACES(PLACE_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_SAVED_USER_PLACE UNIQUE (USER_ID, PLACE_ID)
);

COMMIT;
