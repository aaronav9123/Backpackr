-- ============================================================
-- Backpackr - One-time schema fix-up script
--
-- This is SAFE TO RUN NO MATTER WHAT STATE YOUR DATABASE IS IN.
-- It checks what already exists before adding anything, so it
-- will not error out whether you've already run
-- schema_update_phase1.sql / schema_update_phase2.sql, run them
-- partially, or never run them at all. Every column/table below
-- is only added if it is not already there.
--
-- BUG FIX (Code Review - Deployment gap): if this is a BRAND NEW
-- database (no USERS/PLACES/TRIPS/TRIP_STOPS tables at all yet), run
-- sql/00_base_schema.sql FIRST - it creates those four base tables.
-- This script only ever ALTERs/extends them; it does not create them.
--
-- Run this once, as the same Oracle user Backpackr connects as
-- (see DBConnection.java / config.properties DB_USER - "system" by
-- default), in SQL*Plus, SQL Developer, or any SQL client connected to
-- your XE database.
-- ============================================================

SET SERVEROUTPUT ON

-- ---- BUG FIX (Security - PasswordUtil salted-hash passwords need more
-- room): widen USERS.PASSWORD in case it was created narrower (e.g. a
-- typical VARCHAR2(50) for plain-text passwords) than the ~70 characters
-- the new "<base64 salt>:<base64 hash>" format needs. Widening a
-- VARCHAR2 column is always safe (never truncates existing data), so this
-- is safe to run against any existing USERS table. ----
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE USERS MODIFY (PASSWORD VARCHAR2(200))';
  DBMS_OUTPUT.PUT_LINE('Widened USERS.PASSWORD to VARCHAR2(200)');
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('Could not widen USERS.PASSWORD (already wide enough, or another issue) - skipped: ' || SQLERRM);
END;
/

