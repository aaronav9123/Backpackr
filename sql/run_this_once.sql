-- ---- foreign key PLACES.ADDED_BY -> USERS.USER_ID ----
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE PLACES ADD CONSTRAINT FK_PLACES_ADDED_BY ' ||
                     'FOREIGN KEY (ADDED_BY) REFERENCES USERS(USER_ID)';
  DBMS_OUTPUT.PUT_LINE('Added FK_PLACES_ADDED_BY');
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE NOT IN (-2260, -2264, -2275) THEN RAISE; END IF; -- constraint already exists
  DBMS_OUTPUT.PUT_LINE('FK_PLACES_ADDED_BY already exists - skipped');
END;
/

-- ---- PLACE_IMAGES table ----
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE PLACE_IMAGES (
        IMAGE_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
        PLACE_ID        NUMBER NOT NULL,
        IMAGE_URL       VARCHAR2(500) NOT NULL,
        UPLOADED_BY     NUMBER,
        CREATED_DATE    DATE DEFAULT SYSDATE,
        CONSTRAINT FK_IMG_PLACE FOREIGN KEY (PLACE_ID) REFERENCES PLACES(PLACE_ID) ON DELETE CASCADE,
        CONSTRAINT FK_IMG_USER FOREIGN KEY (UPLOADED_BY) REFERENCES USERS(USER_ID)
    )';
  DBMS_OUTPUT.PUT_LINE('Created PLACE_IMAGES');
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF; -- -955 = name already used by an existing object
  DBMS_OUTPUT.PUT_LINE('PLACE_IMAGES already exists - skipped');
END;
/

