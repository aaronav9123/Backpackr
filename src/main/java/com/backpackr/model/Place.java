package com.backpackr.model;

import java.io.Serializable;
import java.sql.Date;

// BUG FIX / NEW FEATURE (Duplicate-place detection - "contribute to existing
// place" flow): AddPlaceServlet now temporarily stores a not-yet-saved Place
// in the HttpSession while the user decides whether to view the existing
// match or merge their submission into it (see place_exists.jsp). Tomcat can
// serialize session attributes (on redeploy, clustering, or simply passivating
// idle sessions), so this class needs to implement Serializable for that to
// work safely instead of failing at runtime.
public class Place implements Serializable {

    private static final long serialVersionUID = 1L;
    private int placeId;
    private String placeName;
    private String district;
    private String state;
    private String category;
    private String description;
    private double latitude;
    private double longitude;
    private String imageUrl;

    // Phase 1: community contribution fields
    private String address;
    private double avgCost;
    private String openingTime;
    private String bestTime;
    private String mapsLink;
    private Integer addedBy;
    private String addedByName; // joined from USERS, for display
    private Date createdDate;

    // Phase 1: community rating aggregate (computed, not stored directly)
    private double avgRating;
    private int ratingCount;

    // Set by search/list queries for the current viewer (not persisted here)
    private boolean savedByCurrentUser;

    public Place() {
    }

    public int getPlaceId() {
        return placeId;
    }

    public void setPlaceId(int placeId) {
        this.placeId = placeId;
    }

    public String getPlaceName() {
        return placeName;
    }

    public void setPlaceName(String placeName) {
        this.placeName = placeName;
    }

    public String getDistrict() {
        return district;
    }

    public void setDistrict(String district) {
        this.district = district;
    }

    public String getState() {
        return state;
    }

    public void setState(String state) {
        this.state = state;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public double getLatitude() {
        return latitude;
    }

    public void setLatitude(double latitude) {
        this.latitude = latitude;
    }

    public double getLongitude() {
        return longitude;
    }

    public void setLongitude(double longitude) {
        this.longitude = longitude;
    }

    public String getImageUrl() {
        return imageUrl;
    }

    public void setImageUrl(String imageUrl) {
        this.imageUrl = imageUrl;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public double getAvgCost() {
        return avgCost;
    }

    public void setAvgCost(double avgCost) {
        this.avgCost = avgCost;
    }

    public String getOpeningTime() {
        return openingTime;
    }

    public void setOpeningTime(String openingTime) {
        this.openingTime = openingTime;
    }

    public String getBestTime() {
        return bestTime;
    }

    public void setBestTime(String bestTime) {
        this.bestTime = bestTime;
    }

    public String getMapsLink() {
        return mapsLink;
    }

    public void setMapsLink(String mapsLink) {
        this.mapsLink = mapsLink;
    }

    public Integer getAddedBy() {
        return addedBy;
    }

    public void setAddedBy(Integer addedBy) {
        this.addedBy = addedBy;
    }

    public String getAddedByName() {
        return addedByName;
    }

    public void setAddedByName(String addedByName) {
        this.addedByName = addedByName;
    }

    public Date getCreatedDate() {
        return createdDate;
    }

    public void setCreatedDate(Date createdDate) {
        this.createdDate = createdDate;
    }

    public double getAvgRating() {
        return avgRating;
    }

    public void setAvgRating(double avgRating) {
        this.avgRating = avgRating;
    }

    public int getRatingCount() {
        return ratingCount;
    }

    public void setRatingCount(int ratingCount) {
        this.ratingCount = ratingCount;
    }

    public boolean isSavedByCurrentUser() {
        return savedByCurrentUser;
    }

    public void setSavedByCurrentUser(boolean savedByCurrentUser) {
        this.savedByCurrentUser = savedByCurrentUser;
    }
}
