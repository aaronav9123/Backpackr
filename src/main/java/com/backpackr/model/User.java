package com.backpackr.model;

import java.sql.Date;

public class User {

    private int userId;
    private String name;
    private String email;
    private String password;
    private String mobileNumber;
    private Date joinedDate;
    // NEW FEATURE (Profile enhancements): path/URL to an uploaded profile
    // photo, same pattern as Place.imageUrl - null/blank means "use the
    // initial-letter avatar" (the existing fallback everywhere already
    // handles this).
    private String profileImage;

    public User() {
    }

    public int getUserId() {
        return userId;
    }

    public void setUserId(int userId) {
        this.userId = userId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }

    public String getMobileNumber() {
        return mobileNumber;
    }

    public void setMobileNumber(String mobileNumber) {
        this.mobileNumber = mobileNumber;
    }

    public Date getJoinedDate() {
        return joinedDate;
    }

    public void setJoinedDate(Date joinedDate) {
        this.joinedDate = joinedDate;
    }

    public String getProfileImage() {
        return profileImage;
    }

    public void setProfileImage(String profileImage) {
        this.profileImage = profileImage;
    }
}